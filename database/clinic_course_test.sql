-- ---------------------------------------------------------------------
--  Синхронизация счётчиков identity после вставки с явными id
-- ---------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['specialty','post','room','role','service_group','pay_method',
      'drug','service','employee','patient','account','schedule','appointment','visit',
      'invoice','visit_service','referral','prescription','audit']
  LOOP
    EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE(MAX(id), 1)) FROM %I',
                   t, 'id', t);
  END LOOP;
END $$;

