-- ---------------------------------------------------------------------
--  СПРАВОЧНИКИ
-- ---------------------------------------------------------------------
CREATE TABLE specialty (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE post (                       -- должность
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE room (                       -- кабинет
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(10) NOT NULL UNIQUE,
    floor  smallint    NOT NULL
);

CREATE TABLE role (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE service_group (              -- категория услуги
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE pay_method (                 -- способ оплаты
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL UNIQUE
);

CREATE TABLE diagnosis (                  -- справочник МКБ-10
    code varchar(10)  PRIMARY KEY,
    name varchar(300) NOT NULL
);

CREATE TABLE drug (                       -- лекарства
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE
);

CREATE TABLE service (                    -- прайс услуг
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id integer       NOT NULL REFERENCES service_group(id),
    name     varchar(200)  NOT NULL UNIQUE,
    price    numeric(10,2) NOT NULL CHECK (price >= 0),
    is_active boolean      NOT NULL DEFAULT true
);

-- ---------------------------------------------------------------------
--  ЛЮДИ
-- ---------------------------------------------------------------------
CREATE TABLE employee (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name   varchar(50) NOT NULL,
    first_name  varchar(50) NOT NULL,
    middle_name varchar(50),
    post_id     integer     NOT NULL REFERENCES post(id),
    specialty_id integer    REFERENCES specialty(id),
    phone       varchar(20),
    is_active   boolean     NOT NULL DEFAULT true
);

CREATE TABLE patient (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_number  varchar(20)  NOT NULL UNIQUE,
    last_name    varchar(50)  NOT NULL,
    first_name   varchar(50)  NOT NULL,
    middle_name  varchar(50),
    birth_date   date         NOT NULL,
    gender       char(1)      NOT NULL CHECK (gender IN ('М','Ж')),
    snils        varchar(14)  UNIQUE,
    oms_policy   varchar(16)  NOT NULL UNIQUE,
    dms_policy   varchar(20)  UNIQUE,
    address      varchar(200),
    phone        varchar(20),
    created_date date         NOT NULL DEFAULT CURRENT_DATE,
    is_active    boolean      NOT NULL DEFAULT true
);

CREATE TABLE account (                    -- учётная запись
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         varchar(50)  NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role_id       integer      NOT NULL REFERENCES role(id),
    employee_id   integer      UNIQUE REFERENCES employee(id),
    patient_id    integer      UNIQUE REFERENCES patient(id),
    is_active     boolean      NOT NULL DEFAULT true,
    last_login    timestamp,
    -- учётка принадлежит либо сотруднику, либо пациенту
    CHECK ((employee_id IS NULL) <> (patient_id IS NULL))
);

-- Настройка интерфейса привязана к учётной записи.
CREATE TABLE user_theme (
    account_id integer PRIMARY KEY REFERENCES account(id) ON DELETE CASCADE,
    theme varchar(5) NOT NULL DEFAULT 'light' CHECK (theme IN ('light', 'dark')),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
--  РАСПИСАНИЕ И ЗАПИСЬ
-- ---------------------------------------------------------------------
CREATE TABLE schedule (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   integer  NOT NULL REFERENCES employee(id),
    room_id       integer  NOT NULL REFERENCES room(id),
    work_date     date     NOT NULL,
    start_time    time     NOT NULL,
    end_time      time     NOT NULL,
    slot_minutes  integer  NOT NULL CHECK (slot_minutes > 0),
    UNIQUE (employee_id, work_date),
    CHECK (end_time > start_time)
);

CREATE TABLE appointment (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id integer     NOT NULL REFERENCES schedule(id),
    patient_id  integer     NOT NULL REFERENCES patient(id),
    start_time  time        NOT NULL,
    status      varchar(20) NOT NULL DEFAULT 'запланирована'
                CHECK (status IN ('запланирована','завершена','отменена','неявка')),
    source      varchar(20) NOT NULL
                CHECK (source IN ('регистратура','телефон','сайт','приложение')),
    created_at  timestamp   NOT NULL DEFAULT now(),
    UNIQUE (schedule_id, start_time)      -- один слот — одна запись
);

-- ---------------------------------------------------------------------
--  ПРИЁМ
-- ---------------------------------------------------------------------
CREATE TABLE visit (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  integer   NOT NULL UNIQUE REFERENCES appointment(id),
    visited_at      timestamp NOT NULL,
    complaints      text,
    anamnesis       text,
    objective_status text,
    diagnosis_code  varchar(10) REFERENCES diagnosis(code),
    recommendations text,
    is_closed       boolean   NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------
--  ОПЛАТА
--  total в счёте не хранится (это производное значение) — см. v_invoice
-- ---------------------------------------------------------------------
CREATE TABLE invoice (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer     NOT NULL REFERENCES patient(id),
    created_at timestamp   NOT NULL DEFAULT now(),
    status     varchar(20) NOT NULL DEFAULT 'не оплачен'
               CHECK (status IN ('не оплачен','оплачен','отменён')),
    method_id  integer     REFERENCES pay_method(id),
    paid_at    timestamp,
    CHECK ((status = 'оплачен') = (paid_at IS NOT NULL)),
    CHECK (status <> 'оплачен' OR method_id IS NOT NULL)
);

CREATE TABLE visit_service (              -- оказанные услуги
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id    integer       NOT NULL REFERENCES visit(id),
    service_id  integer       NOT NULL REFERENCES service(id),
    invoice_id  integer       REFERENCES invoice(id),
    quantity    integer       NOT NULL DEFAULT 1 CHECK (quantity > 0),
    price       numeric(10,2) NOT NULL CHECK (price >= 0),  -- цена на момент оказания
    rendered_at timestamp     NOT NULL
);

-- ---------------------------------------------------------------------
--  НАПРАВЛЕНИЯ И НАЗНАЧЕНИЯ (дата выдачи = дата приёма, отдельно не хранится)
-- ---------------------------------------------------------------------
CREATE TABLE referral (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id    integer     NOT NULL REFERENCES visit(id),
    service_id  integer     NOT NULL REFERENCES service(id),
    status      varchar(20) NOT NULL DEFAULT 'выдано'
                CHECK (status IN ('выдано','выполнено','отменено')),
    executor_id integer     REFERENCES employee(id),
    done_at     timestamp,
    result      text
);

CREATE TABLE prescription (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id    integer      NOT NULL REFERENCES visit(id),
    drug_id     integer      NOT NULL REFERENCES drug(id),
    dosage      varchar(100),
    instruction text,
    is_recipe   boolean      NOT NULL DEFAULT false   -- true = рецептурный
);

-- ---------------------------------------------------------------------
--  ЖУРНАЛ ДЕЙСТВИЙ
-- ---------------------------------------------------------------------
CREATE TABLE audit (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer     NOT NULL REFERENCES account(id),
    patient_id integer     REFERENCES patient(id),
    acted_at   timestamp   NOT NULL DEFAULT now(),
    action     varchar(20) NOT NULL CHECK (action IN ('SELECT','INSERT','UPDATE','DELETE')),
    table_name varchar(50) NOT NULL,
    record_id  integer
);

-- ---------------------------------------------------------------------
--  ИНДЕКСЫ ПО ВНЕШНИМ КЛЮЧАМ
-- ---------------------------------------------------------------------
CREATE INDEX ix_employee_specialty ON employee(specialty_id);
CREATE INDEX ix_schedule_date      ON schedule(work_date);
CREATE INDEX ix_appointment_patient ON appointment(patient_id);
CREATE INDEX ix_visit_diagnosis    ON visit(diagnosis_code);
CREATE INDEX ix_invoice_patient    ON invoice(patient_id);
CREATE INDEX ix_vs_visit           ON visit_service(visit_id);
CREATE INDEX ix_vs_invoice         ON visit_service(invoice_id);
CREATE INDEX ix_referral_visit     ON referral(visit_id);
CREATE INDEX ix_prescription_visit ON prescription(visit_id);
CREATE INDEX ix_audit_account      ON audit(account_id);
CREATE INDEX ix_audit_patient      ON audit(patient_id);

-- ---------------------------------------------------------------------
--  ПРЕДСТАВЛЕНИЕ: счёт с рассчитанной суммой
-- ---------------------------------------------------------------------
CREATE VIEW v_invoice AS
SELECT i.id,
       i.patient_id,
       i.created_at,
       i.status,
       i.method_id,
       i.paid_at,
       COALESCE(SUM(vs.quantity * vs.price), 0)::numeric(10,2) AS total
FROM invoice i
LEFT JOIN visit_service vs ON vs.invoice_id = i.id
GROUP BY i.id;

